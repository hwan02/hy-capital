-- 내 user_id (이 앱은 혼자 쓴다 — 구역이 제일 많은 계정)
drop table if exists moa_me;
create temp table moa_me as
select user_id from public.zones group by user_id order by count(*) desc limit 1;

do $$ begin
  if not exists (select 1 from moa_me) then
    raise exception 'zones 가 비어 있어 user_id 를 못 찾았다. 먼저 앱에 로그인해 구역을 하나 만들어라.';
  end if;
end $$;

-- 표 ↔ 앱 구역 짝짓기 (자치구가 비어 있는 구역은 키로만 붙인다)
drop table if exists moa_pair;
create temp table moa_pair as
select t.*, z.id as zone_id, z.name as zone_name,
       z.stage as zone_stage, z.rights_date as zone_rights, z.memo as zone_memo
from moa_seoul_2026_09_08 t
left join lateral (
  select z.* from public.zones z, moa_me
  where z.user_id = moa_me.user_id
    and z.kind = '모아타운'
    and public.hy_zone_key(z.name) = t.zkey
    and (z.district is null or z.district = t.district)
  order by z.created_at
  limit 1
) z on true;


-- ════════════════════════════════════════════════════════════
-- ① 확인 — 여기까지 돌리고 결과를 본다 (아무것도 안 바뀐다)
-- ════════════════════════════════════════════════════════════
select
  case
    when zone_id is null                                   then '＋ 추가'
    when stage > coalesce(zone_stage, 0)                   then '↑ 단계 상향'
    when stage < coalesce(zone_stage, 0)
         and coalesce(zone_stage, 0) < 7                   then '⚠ 표와 불일치(메모만)'
    when rights_date is not null
         and rights_date is distinct from zone_rights      then '◔ 권리산정기준일만 교정'
    else '· 그대로'
  end                                        as 할일,
  district                                   as 자치구,
  name                                       as 표_구역,
  zone_name                                  as 앱_구역,
  remark                                     as 표_비고,
  zone_stage                                 as 앱_단계,
  stage                                      as 표_단계,
  zone_rights                                as 앱_권리산정,
  rights_date                                as 표_권리산정
from moa_pair
order by 할일, 자치구, 표_구역;

-- 요약
select
  count(*) filter (where zone_id is null)                              as 추가,
  count(*) filter (where zone_id is not null
                     and rights_date is not null
                     and rights_date is distinct from zone_rights)     as 권리산정_교정,
  count(*) filter (where zone_id is not null
                     and stage > coalesce(zone_stage, 0))              as 단계_상향,
  count(*) filter (where zone_id is not null
                     and stage < coalesce(zone_stage, 0)
                     and coalesce(zone_stage, 0) < 7)                  as 표와_불일치
from moa_pair;


-- ════════════════════════════════════════════════════════════
-- ② 반영 — ①이 괜찮으면 여기부터 돌린다 (여러 번 돌려도 안전)
-- ════════════════════════════════════════════════════════════

-- 1. 권리산정기준일 — 표가 «맞다». 무조건 덮어쓴다.
--    (조합설립 이상 구역도 기준일은 그대로이므로 같이 고친다)
update public.zones z
set rights_date = p.rights_date
from moa_pair p
where z.id = p.zone_id
  and p.rights_date is not null
  and z.rights_date is distinct from p.rights_date;

-- 2. 단계 — «올리기만» 한다.
update public.zones z
set stage            = p.stage,
    stage_source     = p.src,
    stage_checked_at = now()
from moa_pair p
where z.id = p.zone_id
  and p.stage > coalesce(z.stage, 0);

-- 3. 표와 어긋나는 곳 — 내리지 않고 메모만 남긴다.
update public.zones z
set memo = btrim(coalesce(z.memo, '') || E'\n' ||
                 '⚠ 서울시 표(2026-09-08)는 «' || p.remark ||
                 '» 라고 한다 (앱 단계 ' || coalesce(z.stage, 0) ||
                 '). 구청 고시로 확인.')
from moa_pair p
where z.id = p.zone_id
  and p.stage < coalesce(z.stage, 0)
  and coalesce(z.stage, 0) < 7
  and coalesce(z.memo, '') not like '%서울시 표(2026-09-08)는%';

-- 4. 앱에 없는 구역 추가 (26곳이 주민제안 · 19곳이 매수 A 구간)
insert into public.zones (user_id, name, kind, district, stage, stage_source,
                          stage_checked_at, rights_date, memo)
select m.user_id, p.name, '모아타운', p.district, p.stage, p.src, now(),
       p.rights_date,
       '지금 진행 중 — ' || case p.stage
         when 3 then '대상지 선정 — 선정 발표로 오른 구간'
         when 4 then '관리계획 수립 중 — «매수 A»(저점)'
         when 6 then '관리계획 승인고시 완료 — 조합 동의서 걷기 시작'
         else p.remark end
from moa_pair p, moa_me m
where p.zone_id is null
  -- 다시 돌려도 두 번 안 들어가게
  and not exists (
    select 1 from public.zones z
    where z.user_id = m.user_id and z.kind = '모아타운'
      and public.hy_zone_key(z.name) = p.zkey
      and (z.district is null or z.district = p.district)
  );

-- 결과
select count(*) as 모아타운_구역수,
       count(*) filter (where stage = 4) as 매수A_수립중,
       count(*) filter (where rights_date is not null) as 권리산정기준일_있음
from public.zones, moa_me
where zones.user_id = moa_me.user_id and zones.kind = '모아타운';
