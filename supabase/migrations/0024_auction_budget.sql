-- ────────────────────────────────────────────────────────────
-- 경매 예산 — 자금 게이트의 기준값
--
-- financial_snapshots.cash 는 '전체 현금'이라 예비 2호 자금·배당 매수 자금
-- 등 다른 용도가 섞여 있다(2026-08 기준 6,700만원). 경매에 실제로 쓸 수
-- 있는 돈은 그보다 훨씬 적다(강의 메모 기준 약 1,000만원).
--
-- 게이트가 전체 현금을 보면 판정이 느슨해져 "보증금이 되는데?"라고
-- 잘못 통과시킨다. 그래서 경매 전용 예산을 따로 둔다.
-- 0 이면 전체 현금으로 폴백한다(설정 전 상태).
-- ────────────────────────────────────────────────────────────
alter table public.profiles
  add column if not exists auction_budget numeric(16,0) not null default 0;

-- 강의 메모의 '가용 현금 약 1,000만원'을 초기값으로 넣는다.
update public.profiles
set auction_budget = 10000000
where auction_budget = 0;
