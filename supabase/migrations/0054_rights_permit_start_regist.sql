-- ────────────────────────────────────────────────────────────
-- 0054 · 권리산정기준일 판정을 «사업 방식»에 맞게 고친다
--
-- 지금까지 앱은 «사용승인일»만 보고 판정했다. 그게 틀렸다.
-- 교안(부자되는세상) — 「사업 방식 별로 권리산정기준일의 해석이 다르다」:
--
--   신속통합기획(도시정비법) — 권리산정기준일 «다음 날까지»
--                              «소유권 보존등기»가 접수됐으면 OK.
--                              (도정법 §77①: 기준일 다음 날을 기준으로 산정.
--                               구분소유권 확보 여부로 보고, 소유권 «이전»등기는 무관)
--
--   모아타운(빈집법)         — 권리산정기준일«까지» «건축허가»를 받고
--                              «착공신고»를 득했으면 분양대상으로 인정.
--
-- 즉 모아타운은 «허가일·착공신고일», 신통은 «보존등기 접수일»을 봐야 한다.
-- 사용승인일은 셋 중 무엇도 아니다 — 착공보다 한참 뒤, 보존등기보다 앞이다.
-- 그래서 사용승인일로 재면 모아타운에서 «살 수 있는 물건을 못 산다»고
-- 판정해 버린다. 실제로 그렇게 돌고 있었다.
--
-- 사용승인일(approved_on)은 지운다는 뜻이 아니다. «한 방향»으로는 여전히
-- 쓸모 있다(코드 rightsCheck 주석 참조):
--   모아 — 사용승인일 ≤ 기준일 이면 착공은 그보다 앞이니 «확실히 OK».
--   신통 — 사용승인일 > 기준일+1 이면 보존등기는 그 뒤니 «확실히 청산».
-- 반대 방향은 추측이 안 되므로 해당 날짜를 직접 넣어야 한다.
-- ────────────────────────────────────────────────────────────

alter table public.auction_properties
  add column if not exists permit_on date,
  add column if not exists start_on  date,
  add column if not exists regist_on date;

comment on column public.auction_properties.permit_on is
  '건축허가일. 모아타운(빈집법) — 권리산정기준일까지 허가를 받았어야 분양대상.';
comment on column public.auction_properties.start_on is
  '착공신고일. 모아타운(빈집법) — 권리산정기준일까지 착공신고를 득했어야 분양대상.';
comment on column public.auction_properties.regist_on is
  '소유권 보존등기 접수일. 신통기획(도정법) — 권리산정기준일 다음 날까지 접수됐어야 한다.';

comment on column public.auction_properties.approved_on is
  '건축물대장 사용승인일. 단독 판정 기준이 «아니다» — 모아는 허가·착공신고, '
  '신통은 보존등기 접수일로 판정한다. 사용승인일은 한 방향 추론에만 쓴다.';
