/// 단계 하나. `status` 는 auction_properties.status 값과 1:1로 맞춘다.
class Stage {
  final String status;
  final String label;
  final String goal; // 이 단계에서 «끝내야 하는 것» 한 줄
  final IconData icon;
  final Color color;
  final List<StageTask> tasks;

  /// «어떻게» 하는가. 할 일 체크리스트가 아니라 방법이다.
  /// 단계 칩을 누르면 이게 펼쳐진다.
  final List<How> how;

  const Stage({
    required this.status,
    required this.label,
    required this.goal,
    required this.icon,
    required this.color,
    required this.tasks,
    this.how = const [],
  });
}

/// 방법 한 토막.
class How {
  final String title;
  final String body;
  const How(this.title, this.body);
}

/// 할 일 하나. `key` 는 checklist jsonb 의 키.
class StageTask {
  final String key;
  final String label;
  final String? hint; // 왜 / 어떻게 — 모르면 여기서 배운다

