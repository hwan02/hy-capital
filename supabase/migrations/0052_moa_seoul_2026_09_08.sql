-- ── 구역 이름에서 «동 + 번지» 키를 뽑는다 ───────────────────
-- 이름이 제각각이다: 「번동2지역(번동 454번지 일대)」 「화곡6동 957-1 일대」
-- 「면목본동 63-1」 「목동 644-1번지 일대 모아타운 관리계획」.
-- 번지는 «번지/일대/일원/끝»이 뒤따르는 숫자만 인정한다 — 안 그러면
-- 「번동2지역」의 2 를 번지로 읽는다.
create or replace function public.hy_zone_key(nm text)
returns text language plpgsql immutable as $fn$
declare g text[]; d text; l text;
begin
  g := regexp_match(coalesce(nm, ''),
       '([가-힣]{1,4})(?:[0-9]+(?:[·,][0-9]+)*|본)?(동|가)([0-9]+가)?[[:space:]]*([0-9]+(?:-[0-9]+)?)[[:space:]]*(번지|일대|일원|$)');
  if g is not null then
    d := g[1] || g[2] || coalesce(g[3], '');
    l := g[4];
  else
    g := regexp_match(coalesce(nm, ''),
         '([가-힣]{1,4})(?:[0-9]+(?:[·,][0-9]+)*|본)?(동|가)');
    if g is null then
      return btrim(coalesce(nm, ''));
    end if;
    d := g[1] || g[2];
    l := '';
  end if;
  -- 「면목본동」의 본은 앞 글자를 그리디하게 먹고 남는다 → 여기서 턴다.
  d := regexp_replace(d, '본(동|가)$', '\1');
  return d || ' ' || l;
end $fn$;

