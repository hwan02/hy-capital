-- ────────────────────────────────────────────────────────────
-- 0055 · 화곡1동 354 일대 모아타운 — 세부구역을 «실제»로 맞춘다
--
-- 앱에는 A2-1 ~ A2-5 «다섯 개»가 들어 있었고 「매수가능 3/5」로 떴다.
-- 실제 구역은 «셋»이다 — 제2-2 · 제2-3 · 제2-4.
-- 손으로 넣은 값이라 갱신 경로가 없어 그대로 늙어 있었다.
--
-- 【확인한 사실 — 2026-09-19】
-- · 구역 85,462.6㎡ · 기존 1,654가구 → «1,929가구»(임대 479 포함)
-- · 제2-2 · 제2-3 · 제2-4 «3개 가로주택정비사업 구역»으로 구성
-- · 제2-4 조합설립인가 2025.12 / 제2-2 조합설립인가 2026.02
-- · 제2-2 · 제2-4 «시공자 선정 총회 8/22» → 제일건설 (극동건설과 경쟁)
-- · 3개 구역을 «하나의 단지처럼» 개발 — 절차는 각자, 시공사·협력업체 일원화
-- 출처: 데일리한국 2026-08 「제일건설, 화곡1동 모아타운 2개 구역 시공권 확보」
--       뉴스핌 2026-02-13 「서울시, 모아타운 2곳 사업계획 확정…화곡동 1929가구」
--       정비몽땅(A2-2·A2-4 조합설립인가 등록 확인)
--
-- 【A2-1 · A2-5 는 지운다】
-- 공식 자료·정비몽땅 어디에도 없다. 이 둘이 「매수 가능 ★4」로 떠 있어서
-- 「매수가능 3/5」라는 허수가 나왔다. 실제로 살 수 있는 건 «제2-3 하나»다.
--
-- 【제2-3 이 자리다】
-- 셋 중 유일하게 조합설립인가 «전» — 승계 가능. 그런데 양옆(2-2·2-4)은
-- 이미 시공자까지 뽑았고 «한 단지»로 묶인다. 남은 칸이 하나뿐이라는 뜻이다.
-- ────────────────────────────────────────────────────────────

update public.zones
set subs = '[
  {"code":"2-2","status":"시공자 선정 완료 — 2026.08.22 총회, 제일건설 (조합설립인가 2026.02)","rating":""},
  {"code":"2-3","status":"조합설립인가 전 — 매수 가능. 3개 구역 중 유일. 부자되는세상 추천","rating":"5"},
  {"code":"2-4","status":"시공자 선정 완료 — 2026.08.22 총회, 제일건설 (조합설립인가 2025.12)","rating":""}
]'::jsonb,
    memo = btrim(coalesce(memo, '') || E'\n' ||
      '제2-2·2-3·2-4 «3개 구역»으로 구성(앱에 A2-1·A2-5 가 잘못 들어 있었다). ' ||
      '총 1,929가구(임대 479 포함), 기존 1,654가구. 절차는 구역별로 따로 가되 ' ||
      '시공사·협력업체를 일원화해 «하나의 단지»처럼 개발한다. ' ||
      '2-2·2-4 는 2026.08.22 시공자 선정 총회에서 제일건설을 뽑았다. ' ||
      '→ 살 수 있는 건 «2-3» 하나뿐이다. (2026-09-19 확인)')
where kind = '모아타운'
  and public.hy_zone_key(name) = '화곡동 354';

-- 확인 — 세부구역이 3개로 바뀌었나
select name                                   as 구역,
       stage                                  as 단계,
       jsonb_array_length(subs)               as 세부구역수,
       jsonb_path_query_array(subs, '$[*].code') as 코드
from public.zones
where kind = '모아타운'
  and public.hy_zone_key(name) = '화곡동 354';
