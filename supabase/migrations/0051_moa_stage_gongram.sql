-- 모아타운 축에 「주민공람 14일」 칸을 넣는다 (12칸 → 13칸).
--
-- 교안(서울투자반)의 세부 절차가 곧 축이다:
--   관리계획 수립 → 전문가 사전자문 → «주민공람 14일 이상» →
--   관리계획 승인신청 → 위원회 심의(통합심의) → 관리계획 승인 고시
-- 앱은 공람을 칸으로 안 두고 「관리계획 수립」에 뭉쳐 놨었다. 그러면
-- 「지금 공람 중」인 구역을 셀 수가 없다 — 공람 공고는 «값이 뛰기 직전»을
-- 알려주는 신호라 그게 제일 중요하다.
--
-- 「후계공통승」이 3~7번 칸에 그대로 앉는다:
--   3 후보지 선정 · 4 관리계획 수립 · 5 주민공람 · 6 통합심의 · 7 승인고시
--
-- 새 축 (모아타운):
--   1 동의서 징구 시작   2 동의서 달성      3 후보지 선정
--   4 관리계획 수립      5 주민공람 14일     6 통합심의
--   7 관리계획 승인고시   8 조합 동의서 징구   9 조합설립인가
--   10 건축심의·시공자선정 11 사업시행인가    12 이주·착공  13 준공
--
-- 5번 이상은 한 칸씩 뒤로 민다. «내림차순»으로 올려야 값이 겹치지 않는다.
-- 신통기획(11칸)은 축이 달라 건드리지 않는다.

update public.zones set stage = stage + 1
 where kind = '모아타운' and stage >= 5;

